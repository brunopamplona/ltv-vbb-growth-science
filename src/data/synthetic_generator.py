def generate_subscribers(n: int = 10000, seed: int = 42) -> pd.DataFrame:
    """
    Generate synthetic subscriber-level dataset with D7 behavioral signals.

    Returns a DataFrame with columns:
        subscriber_id, plan, acquisition_channel, days_active_d7, plays_d7,
        d7_class, ltv, cac, ltv_cac_ratio
    """
    rng = np.random.default_rng(seed)

    plan_names = list(PLANS.keys())
    plan_weights = [PLANS[p]["monthly_subs"] for p in plan_names]
    plan_weights = np.array(plan_weights) / sum(plan_weights)

    plans = rng.choice(plan_names, size=n, p=plan_weights)
    channels = rng.choice(CHANNELS, size=n, p=[CHANNEL_SPEND_SHARE[c] for c in CHANNELS])

    # Assign D7 class using source-of-truth shares
    class_names = list(D7_CLASSES.keys())
    class_weights = [D7_CLASSES[c]["share"] for c in class_names]
    d7_classes = rng.choice(class_names, size=n, p=class_weights)

    # Generate behavioral signals consistent with class assignment
    days_active = np.zeros(n, dtype=int)
    plays = np.zeros(n, dtype=int)

    for i, cls in enumerate(d7_classes):
        if cls == "Heavy":
            days_active[i] = rng.integers(3, 8)
            plays[i] = rng.integers(2, 15)
        elif cls == "Moderate":
            days_active[i] = rng.integers(1, 3)
            plays[i] = rng.integers(1, 4)
        else:  # Critical
            # Either 0 plays or >4 days without login
            if rng.random() < 0.6:
                days_active[i] = rng.integers(0, 3)
                plays[i] = 0
            else:
                days_active[i] = rng.integers(0, 3)
                plays[i] = rng.integers(0, 2)

    # Compute LTV: plan base × D7 multiplier + noise
    ltvs = np.array([
        PLANS[p]["ltv"] * D7_CLASSES[cls]["ltv_multiplier"] * rng.uniform(0.85, 1.15)
        for p, cls in zip(plans, d7_classes)
    ])
    ltvs = np.clip(ltvs, 5, 500).round(2)

    cacs = np.array([PLANS[p]["cac"] * rng.uniform(0.9, 1.1) for p in plans]).round(2)

    df = pd.DataFrame({
        "subscriber_id": [f"sub_{i:06d}" for i in range(n)],
        "plan": plans,
        "acquisition_channel": channels,
        "days_active_d7": days_active,
        "plays_d7": plays,
        "d7_class": d7_classes,
        "ltv": ltvs,
        "cac": cacs,
        "ltv_cac_ratio": (ltvs / cacs).round(3),
    })
    return df


def generate_retention_curves() -> pd.DataFrame:
    """
    Return monthly retention data for 3 plans matching source-of-truth curves.
    """
    rows = []
    for plan, curve in RETENTION_CURVES.items():
        for month, survival in curve.items():
            rows.append({
                "plan": plan,
                "month": month,
                "survival_rate": survival,
                "cumulative_cancellation": round(1 - survival, 4),
            })
    return pd.DataFrame(rows)


def generate_media_channels(n_months: int = 24, seed: int = 42) -> pd.DataFrame:
    """
    Generate monthly channel-level media spend and conversion data for MMM.
    """
    rng = np.random.default_rng(seed)
    total_monthly_budget = 6_149_000  # R$ benchmark

    rows = []
    for month in range(n_months):
        for channel, share in CHANNEL_SPEND_SHARE.items():
            spend = total_monthly_budget * share * rng.uniform(0.85, 1.20)
            impressions = spend / rng.uniform(0.008, 0.015)
            clicks = impressions * rng.uniform(0.01, 0.04)
            conversions = clicks * rng.uniform(0.015, 0.045)
            revenue = conversions * rng.uniform(60, 120)

            rows.append({
                "month": month + 1,
                "channel": channel,
                "spend_brl": round(spend, 2),
                "impressions": int(impressions),
                "clicks": int(clicks),
                "conversions": int(conversions),
                "revenue_brl": round(revenue, 2),
                "cpa": round(spend / max(conversions, 1), 2),
                "roas": round(revenue / max(spend, 1), 4),
            })

    return pd.DataFrame(rows)


def generate_ab_experiment(n_per_arm: int = 2000, seed: int = 42) -> pd.DataFrame:
    """
    Generate synthetic A/B experiment data: VBB (treatment) vs CPA bidding (control).

    Treatment shifts D7 class mix: +5pp Heavy, -7pp Critical (base scenario).
    """
    rng = np.random.default_rng(seed)

    control_mix = {"Heavy": 0.25, "Moderate": 0.35, "Critical": 0.40}
    treatment_mix = {"Heavy": 0.30, "Moderate": 0.37, "Critical": 0.33}

    rows = []
    for arm, mix in [("control", control_mix), ("treatment", treatment_mix)]:
        class_names = list(mix.keys())
        class_weights = list(mix.values())
        classes = rng.choice(class_names, size=n_per_arm, p=class_weights)

        for cls in classes:
            base_ltv = D7_CLASSES[cls]["base_ltv"] * D7_CLASSES[cls]["ltv_multiplier"]
            ltv = base_ltv * rng.uniform(0.80, 1.20)
            cac = rng.uniform(53, 70) if arm == "control" else rng.uniform(55, 75)
            rows.append({
                "arm": arm,
                "d7_class": cls,
                "ltv": round(ltv, 2),
                "cac": round(cac, 2),
                "converted": 1,
            })

    return pd.DataFrame(rows)


def generate_cohort_data(n_cohorts: int = 12, seed: int = 42) -> pd.DataFrame:
    """
    Generate monthly cohort-level data for financial model validation.
    """
    rng = np.random.default_rng(seed)

    rows = []
    for cohort in range(1, n_cohorts + 1):
        for plan, params in PLANS.items():
            subs = int(params["monthly_subs"] * rng.uniform(0.90, 1.10))
            avg_ltv = params["ltv"] * rng.uniform(0.92, 1.08)
            cac = params["cac"] * rng.uniform(0.95, 1.05)
            rows.append({
                "cohort_month": cohort,
                "plan": plan,
                "new_subscribers": subs,
                "avg_ltv": round(avg_ltv, 2),
                "avg_cac": round(cac, 2),
                "cohort_value_brl": round(subs * avg_ltv, 2),
                "cohort_cost_brl": round(subs * cac, 2),
            })

    return pd.DataFrame(rows)
